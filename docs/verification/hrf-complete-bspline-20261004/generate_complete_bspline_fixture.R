# Independent R oracle for scalafim's complete B-spline HRF basis
# (`Hrfs.bspline(..., includeIntercept = true)`).
#
# Definition under test: a clamped B-spline basis of order degree + 1 on
# [0, span] with W = max(nBasis, degree + 1) columns and W - degree - 1
# interior knots uniformly spaced over the actual span. In R this is
#   splines::bs(t, knots = <uniform interior>, degree = degree,
#               intercept = TRUE, Boundary.knots = c(0, span))
#
# Usage (from the repository root):
#   Rscript docs/verification/hrf-complete-bspline-20261004/generate_complete_bspline_fixture.R \
#     [path/to/fmrihrf checkout]
#
# Writes the Scala fixture object and prints the fmrihrf cross-checks.

source("tools/r-parity/receipt_serialization.R")

args <- commandArgs(trailingOnly = TRUE)
fmrihrf_dir <- if (length(args) >= 1L) args[[1L]] else path.expand("~/code/fmrihrf")
out_path <- "modules/hrf/shared/src/test/scala/scalafim/fmri/hrf/fixtures/CompleteBsplineRFixtures.scala"

complete_bs <- function(t, span, n_basis, degree) {
  width <- max(n_basis, degree + 1L)
  intervals <- width - degree
  interior <- if (intervals > 1L) span * seq_len(intervals - 1L) / intervals else numeric(0)
  splines::bs(t, knots = interior, degree = degree, intercept = TRUE,
              Boundary.knots = c(0, span))
}

configs <- list(
  list(name = "cubic5_span24_5", n_basis = 5L, degree = 3L, span = 24.5),
  list(name = "cubic8_span24", n_basis = 8L, degree = 3L, span = 24),
  list(name = "quadratic6_span17_3", n_basis = 6L, degree = 2L, span = 17.3),
  list(name = "linear4_span10", n_basis = 4L, degree = 1L, span = 10),
  list(name = "quartic12_span32_75", n_basis = 12L, degree = 4L, span = 32.75),
  list(name = "cubic2_minimum_span7_75", n_basis = 2L, degree = 3L, span = 7.75)
)

# In-support times only: every knot, every midpoint, both endpoints and an
# irrational offset. Out-of-support zeros are a scalafim policy, not R's.
times_for <- function(span, width, degree) {
  intervals <- width - degree
  grid <- span * seq(0, 2L * intervals) / (2L * intervals)
  extra <- span * c(1 / pi, 1 / sqrt(2), exp(-1), 0.999999)
  # Canonicalize before evaluating so the serialized times are exactly the
  # points R evaluated at.
  canonicalize_receipt_numbers(sort(unique(c(grid, extra))))
}

fixtures <- lapply(configs, function(cfg) {
  width <- max(cfg$n_basis, cfg$degree + 1L)
  times <- times_for(cfg$span, width, cfg$degree)
  values <- complete_bs(times, cfg$span, cfg$n_basis, cfg$degree)
  stopifnot(ncol(values) == width)
  stopifnot(max(abs(rowSums(values) - 1)) < 1e-14)
  c(cfg, list(width = width, times = times, values = as.vector(t(values))))
})

fmt <- function(x) paste(receipt_format_number(x), collapse = ", ")

lines <- c(
