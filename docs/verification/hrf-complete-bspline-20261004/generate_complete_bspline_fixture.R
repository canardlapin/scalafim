  "",
  "// Generated by docs/verification/hrf-complete-bspline-20261004/generate_complete_bspline_fixture.R",
  sprintf("// with %s, splines %s. Do not edit by hand.", R.version.string,
          as.character(packageVersion("splines"))),
  sprintf("// Numbers: %s.", receipt_serialization_convention()),
