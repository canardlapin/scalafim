# ---- fmrihrf cross-checks (reported in the receipt; not part of the fixture) ----
cat("installed fmrihrf: ", as.character(packageVersion("fmrihrf")), "\n", sep = "")

# Installed 0.4.0 hrf_bspline is the legacy convention (drops only the first
# spline). It is not the complete basis: it cannot reproduce a constant.
legacy <- fmrihrf::hrf_bspline(seq(0, 24, by = 0.5), span = 24, N = 5, degree = 3)
cat(sprintf("installed legacy: ncol = %d, row-sum range = %s\n", ncol(legacy),
            paste(format(range(rowSums(legacy)), digits = 6), collapse = " .. ")))

# The fmrihrf checkout's current hrf_bspline (unreleased, N + 2 clamped basis
# with first and last splines dropped) is the complete basis of width N + 2
# with its two boundary columns removed.
src_file <- file.path(fmrihrf_dir, "R", "hrf-functions.R")
if (file.exists(src_file)) {
  env <- new.env()
  exprs <- parse(src_file)
  for (e in exprs) {
    if (is.call(e) && identical(e[[1L]], as.name("<-")) &&
        identical(e[[2L]], as.name("hrf_bspline"))) eval(e, env)
  }
  sha <- tryCatch(system2("git", c("-C", fmrihrf_dir, "rev-parse", "--short", "HEAD"),
                          stdout = TRUE), error = function(e) "unknown")
  worst <- 0
  for (cfg in list(c(3L, 3L, 24), c(5L, 3L, 24.5), c(6L, 2L, 17.3), c(10L, 4L, 32.75))) {
    N <- cfg[[1L]]; degree <- cfg[[2L]]; span <- cfg[[3L]]
    t <- seq(0, span, length.out = 97L)
    head_basis <- env$hrf_bspline(t, span = span, N = N, degree = degree)
    full <- complete_bs(t, span, N + 2L, degree)
    worst <- max(worst, max(abs(head_basis - full[, -c(1L, ncol(full)), drop = FALSE])))
  }
  cat(sprintf("fmrihrf checkout %s hrf_bspline(N) vs complete(N + 2)[, -c(1, last)]: max |diff| = %.3g\n",
              sha, worst))
} else {
  cat("fmrihrf checkout not found at", fmrihrf_dir, "\n")
}
