  "// Oracle: splines::bs(t, knots = uniform interior knots over span, degree,",
  "//   intercept = TRUE, Boundary.knots = c(0, span)).",
  "object CompleteBsplineRFixtures:",
  "",
  "  /** `values` is row-major: times.length rows by `width` columns. */",
  "  final case class Fixture(",
  "      name: String,",
  "      nBasis: Int,",
  "      degree: Int,",
  "      span: Double,",
  "      width: Int,",
  "      times: Vector[Double],",
  "      values: Vector[Double]",
  "  ):",
  "    def at(timeIndex: Int, basis: Int): Double = values(timeIndex * width + basis)",
  "",
  "  val all: Vector[Fixture] = Vector("
)
entries <- vapply(fixtures, function(f) {
  sprintf(paste0("    Fixture(name = \"%s\", nBasis = %d, degree = %d, span = %s, width = %d,\n",
                 "      times = Vector(%s),\n      values = Vector(%s))"),
          f$name, f$n_basis, f$degree, receipt_format_number(f$span), f$width,
          fmt(f$times), fmt(f$values))
}, character(1))
lines <- c(lines, paste(entries, collapse = ",\n"), "  )")
