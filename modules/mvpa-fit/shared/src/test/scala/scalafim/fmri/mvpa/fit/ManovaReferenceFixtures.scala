    out.result()

  private def fromRows(rows: Vector[Vector[Double]]): DMat =
    val out = Matrix.newBuilder(rows.length, rows.head.length)
    var row = 0
    while row < rows.length do
      var col = 0
      while col < rows.head.length do
        out(row, col) = rows(row)(col)
        col += 1
      row += 1
    out.result()
