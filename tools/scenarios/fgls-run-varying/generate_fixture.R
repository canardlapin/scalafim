retention <- .5
case_values <- function(restart, pooled) {
  raw <- rbind(c(.42, -.12), c(.30, .05))
  mean <- colSums(raw * runs) / sum(runs)
  shrunk <- retention * raw + (1 - retention) * matrix(mean, 2, 2, byrow = TRUE)
  phis <- lapply(1:2, function(i) shrunk[i, ])
  Xd <- cbind(X, sapply(censor, function(cr) as.numeric(t0 == cr)))
  W <- W_build(phis, FALSE); Z <- W %*% Xd; zy <- W %*% y
  beta <- solve(crossprod(Z), crossprod(Z, zy))
  s2 <- sum((zy - Z %*% beta)^2) / (n - ncol(Xd))
  vinv <- function(th) crossprod(W_build(list(th[2:3], th[4:5]), FALSE)) / th[1]
  A <- diag(5)
  for (r in 1:2) for (s in 1:2) for (lag in 1:2)
    A[1 + 2*(r-1) + lag, 1 + 2*(s-1) + lag] <- retention * (r == s) + (1-retention) * runs[s] / sum(runs)
  k <- generic_kr(Xd, vinv, c(s2, phis[[1]], phis[[2]]), A)
  L1 <- matrix(c(1, 0, rep(0, ncol(Xd)-2)), 1)
  L2 <- rbind(L1, c(0, 1, rep(0, ncol(Xd)-2)))
  list(sigma2=s2, beta=beta[1:4], phiA=k$PhiA[1:4,1:4], phiCond=k$Phi[1:4,1:4],
       t=kr_moments(k,L1), f=kr_moments(k,L2))
}
